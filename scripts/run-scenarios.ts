/**
 * Runs the scenarios of tests/scenarios.json through the REAL chat handler with the REAL model and the in-memory repo, checks the
 * invariants (src/testing/invariants.ts) after every employee turn, and writes docs/scenario-report.md and
 * docs/scenario-transcript.json.
 *
 *   pnpm scenarios                     run (at most --max-calls model requests, then pause)
 *   pnpm scenarios --resume            continue after the last finished scenario (state: .scenario-state.json, git-ignored)
 *   pnpm scenarios --only <id>         run one scenario
 *   pnpm scenarios --max-calls 30      model request budget for this run (default 12)
 *
 * It spends real model quota, so it never runs in CI (CI=true refuses), and it pauses cleanly on quota (429), 418, timeouts and
 * "all providers failed". It never touches Supabase (the in-memory repo is installed before anything else and the Supabase
 * variables are removed), uses a fresh random session secret and representative code, and never prints keys or codes.
 */
import { randomBytes } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { z } from 'zod';

// ---- environment first: memory repo only, throw-away secrets, no Supabase -------------------------------------------------------
try {
  process.loadEnvFile('.env.local'); // model keys only; the secrets below always replace whatever the file holds
} catch {
  /* no .env.local: keys may come from the shell */
}
for (const k of Object.keys(process.env)) if (k.startsWith('SUPABASE') || k.startsWith('NEXT_PUBLIC_SUPABASE')) delete process.env[k];
process.env.REPO_MODE = 'memory';
process.env.SESSION_SECRET = randomBytes(32).toString('hex');
process.env.REP_ACCESS_CODE = randomBytes(12).toString('hex');

const NEUTRAL = 'לא הצלחתי לענות כמו שצריך. אפשר לנסח את השאלה מחדש או לספר לי מה חסר?';
const ROOT = process.cwd();
const STATE_FILE = path.join(ROOT, '.scenario-state.json');
const REPORT_FILE = path.join(ROOT, 'docs', 'scenario-report.md');
const TRANSCRIPT_FILE = path.join(ROOT, 'docs', 'scenario-transcript.json');

const ScenarioFile = z.object({
  scenarios: z.array(
    z.object({
      id: z.string(),
      description: z.string(),
      turns: z.array(
        z.union([
          z.object({ employee: z.string() }).strict(),
          z.object({ rep: z.object({ kind: z.string().optional(), field: z.string().optional(), typed: z.string().optional(), text: z.string().optional() }).strict() }).strict(),
        ]),
      ),
    }),
  ),
});

interface TurnRecord {
  n: number;
  kind: 'employee' | 'rep';
  message: string;
  assistantText: string;
  status: number;
  latencyMs: number;
  modelCalls: number;
  replaced: boolean;
  replacedVia: string | null;
  replacedReason: string | null;
  genericFallback: boolean;
  openQuestions: string[];
  violations: { invariant: string; message: string }[];
}
interface ScenarioResult {
  id: string;
  description: string;
  finished: boolean;
  turns: TurnRecord[];
}
interface RunState {
  results: Record<string, ScenarioResult>;
  pausedBecause?: string;
}

function parseArgs(argv: string[]) {
  const get = (flag: string) => {
    const i = argv.indexOf(flag);
    return i >= 0 ? argv[i + 1] : undefined;
  };
  const max = Number(get('--max-calls') ?? 12);
  return { resume: argv.includes('--resume'), only: get('--only'), maxCalls: Number.isFinite(max) && max > 0 ? max : 12 };
}

const PAUSE_PATTERN = /status (429|418|408|5\d\d)|timeout|timed out|quota|rate.?limit|all_providers_failed/i;

function writeReports(state: RunState, order: string[]) {
  const results = order.map((id) => state.results[id]).filter((r): r is ScenarioResult => r !== undefined);
  const turns = results.flatMap((r) => r.turns.filter((t) => t.kind === 'employee'));
  const violations = results.flatMap((r) => r.turns.flatMap((t) => t.violations.map((v) => ({ id: r.id, n: t.n, ...v }))));
  const replaced = turns.filter((t) => t.replaced).length;
  const generic = turns.filter((t) => t.genericFallback).length;
  const lat = turns.map((t) => t.latencyMs).sort((a, b) => a - b);
  const pct = (n: number) => (turns.length === 0 ? '0%' : `${((100 * n) / turns.length).toFixed(1)}%`);
  const lines = [
    '# Scenario report',
    '',
    `Generated by \`pnpm scenarios\` (real model, in-memory repo). ${state.pausedBecause ? `**Paused:** ${state.pausedBecause}` : 'Run finished or stopped by the budget.'}`,
    '',
    `- Scenarios with a result: ${results.length} of ${order.length} (finished: ${results.filter((r) => r.finished).length})`,
    `- Employee turns: ${turns.length}`,
    `- Invariant violations: **${violations.length}**`,
    `- Guard / empty-answer replacements: ${replaced} (${pct(replaced)}); generic fallback text: ${generic} (${pct(generic)})`,
    `- Latency per turn: median ${lat[Math.floor(lat.length / 2)] ?? 0} ms, max ${lat.at(-1) ?? 0} ms`,
    '',
    '## Violations',
    '',
    ...(violations.length === 0 ? ['None.'] : violations.map((v) => `- ${v.id} turn ${v.n}: (${v.invariant}) ${v.message}`)),
    '',
    '## Scenarios',
    '',
  ];
  for (const r of results) {
    lines.push(`### ${r.id}${r.finished ? '' : ' (not finished)'}`, '', r.description, '');
    for (const t of r.turns) {
      lines.push(`${t.n}. **${t.kind === 'rep' ? 'Representative' : 'Employee'}:** ${t.message}`);
      if (t.kind === 'employee') {
        lines.push(`   - Assistant: ${t.assistantText.replace(/\n/g, ' / ')}`);
        lines.push(`   - status ${t.status}, ${t.latencyMs} ms, ${t.modelCalls} model requests, open questions: ${t.openQuestions.join(', ') || 'none'}${t.replaced ? `, REPLACED (${t.replacedReason}, ${t.replacedVia})` : ''}${t.genericFallback ? ', GENERIC FALLBACK' : ''}`);
      } else lines.push(`   - ${t.assistantText}`);
      for (const v of t.violations) lines.push(`   - VIOLATION (${v.invariant}): ${v.message}`);
    }
    lines.push('');
  }
  fs.mkdirSync(path.dirname(REPORT_FILE), { recursive: true });
  fs.writeFileSync(REPORT_FILE, lines.join('\n'));
  fs.writeFileSync(TRANSCRIPT_FILE, JSON.stringify({ pausedBecause: state.pausedBecause ?? null, scenarios: results }, null, 2));
}

async function main() {
  if (process.env.CI) {
    console.log('pnpm scenarios spends real model quota and does not run in CI. Nothing was done.');
    return;
  }
  const args = parseArgs(process.argv.slice(2));
  const all = ScenarioFile.parse(JSON.parse(fs.readFileSync(path.join(ROOT, 'tests', 'scenarios.json'), 'utf8'))).scenarios;
  const order = all.map((s) => s.id);
  if (args.only && !order.includes(args.only)) throw new Error(`unknown scenario "${args.only}"`);

  // modules that read the environment are loaded only now
  const { createMemoryRepo } = await import('../src/db/memoryRepo');
  const { setRepo } = await import('../src/db/repo');
  const { buildProviders } = await import('../src/agent/providers');
  const { createInterpreter } = await import('../src/agent/interpretRepText');
  const { ConversationDriver } = await import('../src/testing/driver');
  const { checkTurn, checkState } = await import('../src/testing/invariants');
  const { recordProviders } = await import('../src/testing/recorder');

  const providers = buildProviders(process.env);
  if (providers.length === 0) {
    console.log('No model key is configured (GEMINI_API_KEY, GROQ_API_KEY or OPENROUTER_API_KEY in .env.local). Nothing was run.');
    return;
  }
  console.log(`Providers: ${providers.map((p) => p.name).join(', ')}. Budget: ${args.maxCalls} model requests.`);

  const state: RunState = args.resume && fs.existsSync(STATE_FILE) ? (JSON.parse(fs.readFileSync(STATE_FILE, 'utf8')) as RunState) : { results: {} };
  delete state.pausedBecause;
  const save = () => {
    fs.writeFileSync(STATE_FILE, JSON.stringify(state));
    writeReports(state, order);
  };

  let used = 0;
  const interpreterCalls: unknown[] = [];
  const interpreter = createInterpreter(recordProviders(providers, interpreterCalls as never[]));
  const todo = all.filter((s) => (args.only ? s.id === args.only : !state.results[s.id]?.finished));

  outer: for (const sc of todo) {
    if (used >= args.maxCalls) {
      state.pausedBecause = `model request budget (${args.maxCalls}) reached; run again with --resume`;
      break;
    }
    setRepo(createMemoryRepo()); // a fresh in-memory employee for every scenario
    const driver = await ConversationDriver.start();
    const result: ScenarioResult = { id: sc.id, description: sc.description, finished: false, turns: [] };
    state.results[sc.id] = result;
    let n = 0;
    for (const turn of sc.turns) {
      n++;
      if (used >= args.maxCalls) {
        state.pausedBecause = `model request budget (${args.maxCalls}) reached inside ${sc.id}; that scenario restarts on --resume`;
        delete state.results[sc.id];
        break outer;
      }
      if ('rep' in turn) {
        const q = await driver.findOpen({ kind: turn.rep.kind, field: turn.rep.field });
        const before = interpreterCalls.length;
        const reply = turn.rep.typed !== undefined ? await driver.repAnswerTyped(q.id, turn.rep.typed) : await driver.repAnswerText(q.id, turn.rep.text ?? '', interpreter);
        used += interpreterCalls.length - before;
        const st = await driver.employeeState();
        const views = await driver.repQuestions();
        const violations = checkState({ response: {}, state: st, repViews: views, repTexts: driver.repTexts, interpreterInputs: driver.interpreterInputs });
        result.turns.push({
          n, kind: 'rep', message: `[${q.kind}/${q.field}] ${turn.rep.typed !== undefined ? 'typed answer' : 'free text'}`, assistantText: `status ${reply.status}, interpretation: ${reply.body?.interpretation ?? 'n/a'}`,
          status: reply.status, latencyMs: 0, modelCalls: interpreterCalls.length - before, replaced: false, replacedVia: null, replacedReason: null, genericFallback: false,
          openQuestions: views.filter((v) => v.status === 'open').map((v) => `${v.kind}/${v.field}`), violations,
        });
        continue;
      }
      const obs = await driver.chat(turn.employee, providers, { interpret: interpreter, fallback: { retries: 1, baseDelayMs: 2000 } });
      used += obs.modelCalls.length;
      const logText = obs.logs.join('\n');
      const violations = obs.status === 200 ? checkTurn({ ...obs, repTexts: driver.repTexts, interpreterInputs: driver.interpreterInputs }) : [];
      result.turns.push({
        n, kind: 'employee', message: turn.employee, assistantText: obs.assistantText, status: obs.status, latencyMs: obs.latencyMs, modelCalls: obs.modelCalls.length,
        replaced: obs.replaced, replacedVia: obs.replacedVia, replacedReason: obs.replacedReason, genericFallback: obs.assistantText === NEUTRAL,
        openQuestions: obs.repViews.filter((v) => v.status === 'open').map((v) => `${v.kind}/${v.field}`), violations,
      });
      save();
      if (obs.status === 503 || obs.status === 429 || PAUSE_PATTERN.test(logText)) {
        if (obs.status !== 200) {
          state.pausedBecause = `the model providers are busy or out of quota (HTTP ${obs.status}) in ${sc.id}; wait and run again with --resume`;
          result.turns.pop();
          delete state.results[sc.id];
          break outer;
        }
      }
    }
    result.finished = true;
    save();
  }
  save();
  const done = Object.values(state.results).filter((r) => r.finished).length;
  console.log(state.pausedBecause ? `Paused: ${state.pausedBecause}` : 'Done.');
  console.log(`Finished scenarios: ${done} of ${order.length}. Model requests used this run: ${used}. Report: docs/scenario-report.md`);
}

main().catch((err) => {
  // never print anything that could hold a key: the class and the message of OUR errors only
  console.error(`scenario run failed: ${err instanceof Error ? err.name : 'unknown'}: ${err instanceof Error ? err.message.slice(0, 200) : ''}`);
  process.exitCode = 1;
});
