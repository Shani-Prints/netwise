import { wrapLanguageModel } from 'ai';
import type { ProviderEntry } from '../agent/providers';

/**
 * Records every model request of a turn (the prompt the employee-facing model really saw, including the SERVER STATE block
 * and the tool results of earlier steps) by wrapping the provider models. Works for fake models and for real ones, and never
 * changes what the model receives or returns. Used by the golden runner and by the scenario runner.
 */

export interface RecordedCall {
  /** The prompt messages of this request (system, user, assistant, tool). */
  prompt: PromptMessage[];
  startedAt: number;
  ms: number;
  failed: boolean;
}

export interface PromptMessage {
  role: string;
  content: unknown;
}

export function recordProviders(providers: ProviderEntry[], sink: RecordedCall[]): ProviderEntry[] {
  return providers.map((p) => {
    if (typeof p.model === 'string') throw new Error('recordProviders needs a model object, not a model id');
    const model = wrapLanguageModel({
      model: p.model,
      middleware: {
        wrapGenerate: async ({ doGenerate, params }) => {
          const call: RecordedCall = { prompt: params.prompt as unknown as PromptMessage[], startedAt: Date.now(), ms: 0, failed: false };
          sink.push(call);
          try {
            return await doGenerate();
          } catch (err) {
            call.failed = true;
            throw err;
          } finally {
            call.ms = Date.now() - call.startedAt;
          }
        },
      },
    });
    return { ...p, model };
  });
}

const STATE_HEADER = 'SERVER STATE (trusted, generated by the server for this turn)';

const textOf = (content: unknown): string =>
  typeof content === 'string'
    ? content
    : Array.isArray(content)
      ? content.map((part) => (part && typeof part === 'object' && 'text' in part ? String((part as { text: unknown }).text) : '')).join('\n')
      : '';

/** The SERVER STATE block of the first request that carried one (the block is generated once per turn). */
export function stateBlockOf(calls: RecordedCall[]): string {
  for (const c of calls) {
    for (const m of c.prompt) {
      if (m.role !== 'system') continue;
      const text = textOf(m.content);
      const at = text.indexOf(STATE_HEADER);
      if (at >= 0) return text.slice(at + STATE_HEADER.length).trim();
    }
  }
  return '';
}

/** Every tool output of the turn: the tool results are echoed back to the model in its next request, so the LAST request has them all. */
export function toolOutputsOf(calls: RecordedCall[]): unknown[] {
  const last = [...calls].reverse().find((c) => c.prompt.some((m) => m.role === 'tool'));
  if (!last) return [];
  const out: unknown[] = [];
  for (const m of last.prompt) {
    if (m.role !== 'tool' || !Array.isArray(m.content)) continue;
    for (const part of m.content as { type?: string; output?: { type?: string; value?: unknown } }[]) {
      if (part?.type !== 'tool-result') continue;
      const o = part.output;
      out.push(o && typeof o === 'object' && 'value' in o ? o.value : o);
    }
  }
  return out;
}

/** Everything the employee-facing model was shown in this turn, as plain text (for "never saw this text" checks). */
export function promptTextOf(calls: RecordedCall[]): string {
  return calls.map((c) => JSON.stringify(c.prompt)).join('\n');
}
